#!/usr/bin/env python3
"""Builds SUMMARY.md from speed.csv, memory.csv and size.csv in a results directory."""
import csv, math, os, sys
from collections import defaultdict

out = sys.argv[1]
LIBNAMES = {"fftchode": "fftchode", "fftw-scalar": "FFTW scalar", "fftw-simd": "FFTW SIMD",
            "pocketfft": "pocketfft", "kissfft": "KissFFT", "ffte": "FFTE"}
ORDER = list(LIBNAMES)
SHOW = [2, 64, 1024, 65536, 1048576, 6, 1000, 27000, 165375, 1000003]


def rd(name):
    p = os.path.join(out, name)
    if not os.path.exists(p):
        return []
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def fnum(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def fmt_mf(r):
    if r is None:
        return "-"
    if r["status"] == "ok":
        return "%.0f (%.0f)" % (float(r["mflops_median"]), float(r["mflops_best"]))
    return "n/a" if r["status"] in ("n/a", "verify-fail") else r["status"]


speed = rd("speed.csv")
mem = rd("memory.csv")
size = rd("size.csv")
L = []
L.append("# Benchmark summary\n")
L.append("Generated by bench/scripts/summarize.py from the CSVs in this directory (see ENV.txt for the machine, "
         "toolchain and pinned versions; bench/README.md for methodology). Raw per-trial data is in speed.csv.\n")

if speed:
    idx = {}
    for r in speed:
        idx[(r["lib"], r["precision"], r["kind"], int(r["threads"]), int(r["n"]))] = r
    libs = [l for l in ORDER if any(k[0] == l for k in idx)]
    configs = sorted({(k[2], k[1], k[3]) for k in idx}, key=lambda c: (c[0], c[1] != "double", c[2]))
    sizes_all = sorted({k[4] for k in idx})
    show = [n for n in SHOW if n in sizes_all] or sizes_all[:10]
    L.append("## Speed (median mflops over trials, best trial in parentheses; mflops = 5 N log2 N / t complex, 2.5 N log2 N / t real)\n")
    L.append("n/a = unsupported by that library (reason in speed.csv note column) or failed benchFFT verification; "
             "'-' = library not run in that configuration (e.g. no threading support).\n")
    for kind, prec, th in configs:
        L.append("### %s, %s precision, threads=%d\n" % ("complex forward (c2c)" if kind == "c2c" else "real forward (r2c)", prec, th))
        have = [l for l in libs if any((l, prec, kind, th, n) in idx for n in show)]
        if not have:
            continue
        L.append("| N | " + " | ".join(LIBNAMES[l] for l in have) + " |")
        L.append("|---:|" + "---:|" * len(have))
        for n in show:
            L.append("| %d | " % n + " | ".join(fmt_mf(idx.get((l, prec, kind, th, n))) for l in have) + " |")
        L.append("")
    ok1 = sorted((float(r["mflops_best"]) - float(r["mflops_worst"])) / float(r["mflops_median"])
                 for r in speed if r["status"] == "ok" and r["threads"] == "1")
    if ok1:
        L.append("Run-to-run noise: within a cell the spread (best - worst trial) / median has median %.0f%% and 90th percentile %.0f%% "
                 "over all threads=1 cells (shared cloud VM), so differences of roughly 10%% between two libraries at a single size are not significant; "
                 "the geometric means below average over many sizes.\n" % (100 * ok1[len(ok1) // 2], 100 * ok1[int(len(ok1) * 0.9)]))
    L.append("### Geometric-mean speed ratio over all sizes both libraries ran (median mflops, threads=1 unless noted)\n")
    L.append("Ratio of the row library to FFTW scalar (upstream FFTW 3.3.10 scalar build, same flags).\n")
    L.append("| kind | precision | threads | " + " | ".join(LIBNAMES[l] + " / FFTW scalar" for l in libs if l != "fftw-scalar") + " |")
    L.append("|---|---|---:|" + "---:|" * (len(libs) - 1))
    for kind, prec, th in configs:
        cells = []
        for l in libs:
            if l == "fftw-scalar":
                continue
            rs = []
            for n in sizes_all:
                a, b = idx.get((l, prec, kind, th, n)), idx.get(("fftw-scalar", prec, kind, th, n))
                if a and b and a["status"] == "ok" and b["status"] == "ok":
                    rs.append(math.log(float(a["mflops_median"]) / float(b["mflops_median"])))
            cells.append("%.3f (%d sizes)" % (math.exp(sum(rs) / len(rs)), len(rs)) if rs else "-")
        L.append("| %s | %s | %d | " % (kind, prec, th) + " | ".join(cells) + " |")
    L.append("")
    L.append("### Plan time, threads=1, double (cold plan in a fresh process, microseconds)\n")
    have = [l for l in libs if any((l, "double", "c2c", 1, n) in idx for n in show)]
    L.append("| kind | N | " + " | ".join(LIBNAMES[l] for l in have) + " |")
    L.append("|---|---:|" + "---:|" * len(have))
    for kind in ("c2c", "r2c"):
        for n in [n for n in show if n in (64, 1024, 65536, 1048576, 1000003)]:
            cs = []
            for l in have:
                r = idx.get((l, "double", kind, 1, n))
                cs.append("%.1f" % (float(r["plan_cold_s"]) * 1e6) if r and r["status"] == "ok" else "n/a")
            L.append("| %s | %d | " % (kind, n) + " | ".join(cs) + " |")
    L.append("\npocketfft has no separate plan step: its time is plan + one execution (plan cache enabled).\n")

if mem:
    idx = {(r["lib"], r["precision"], r["kind"], int(r["threads"]), int(r["n"])): r for r in mem}
    msizes = sorted({k[4] for k in idx})
    mlibs = [l for l in ORDER if any(k[0] == l for k in idx)]
    L.append("## Memory (one plan + one execute in a fresh process; sizes in KiB)\n")
    L.append("heap = bytes live in malloc-family allocations above the user's input/output buffers, peak over plan+execute "
             "(link-time malloc interposer, malloc_usable_size; excludes thread stacks and static data). "
             "RSS = ru_maxrss (peak resident set) of the whole process minus the same measurement for a do-nothing benchee at the same size "
             "(removes the input/output buffers and process baseline; includes library code pages touched, static tables and thread stacks).\n")
    for kind in ("c2c", "r2c"):
        for prec in ("double", "single"):
            for th in sorted({k[3] for k in idx}):
                have = [l for l in mlibs if l != "null" and any((l, prec, kind, th, n) in idx for n in msizes)]
                if not have:
                    continue
                L.append("### %s %s threads=%d: peak heap overhead (plan+execute) / RSS above baseline, KiB\n" % (kind, prec, th))
                L.append("| N | " + " | ".join(LIBNAMES[l] for l in have) + " |")
                L.append("|---:|" + "---:|" * len(have))
                for n in msizes:
                    base = idx.get(("null", prec, kind, 1, n))
                    cs = []
                    for l in have:
                        r = idx.get((l, prec, kind, th, n))
                        if not r or r["status"] != "ok":
                            cs.append("n/a")
                            continue
                        heap = int(r["heap_peak_plan_exec_bytes"]) / 1024.0
                        rss = (int(r["ru_maxrss_kb"]) - int(base["ru_maxrss_kb"])) if base and base["status"] == "ok" else None
                        cs.append("%.0f / %s" % (heap, "%d" % rss if rss is not None else "?"))
                    L.append("| %d | " % n + " | ".join(cs) + " |")
                L.append("")

if size:
    L.append("## Compiled size (bytes)\n")
    L.append("Library artifact = the object/archive that carries the library code (fftchode: build/fftchode.o holds both precisions and threads; "
             "FFTW: libfftw3.a / libfftw3f.a with threads combined; pocketfft: header-only, so the object compiled from the benchee that instantiates "
             "c2c/r2c; KissFFT: kiss_fft.o + kiss_fftr.o; FFTE: 1-D complex routines only). "
             "text/data/bss from size(1) totals. Binary = stripped static benchmark binary; 'minus null' subtracts the same driver "
             "linked with a do-nothing benchee (libbench + libc + driver). Binaries are linked without --gc-sections.\n")
    L.append("| library | precision | artifact | file bytes | text | data | bss | stripped binary | binary minus null |")
    L.append("|---|---|---|---:|---:|---:|---:|---:|---:|")
    for r in sorted(size, key=lambda r: (ORDER.index(r["lib"]), r["precision"] != "double")):
        L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            LIBNAMES[r["lib"]], r["precision"], r["artifact"], r["artifact_file_bytes"], r["text"], r["data"], r["bss"],
            r["stripped_binary_bytes"], r["binary_minus_null_bytes"]))
    L.append("")
    L.append("Both precisions together (file bytes of the library artifacts, and stripped binaries are per precision as above):\n")
    L.append("| library | double + single artifact bytes | double + single text |")
    L.append("|---|---:|---:|")
    for lib in ORDER:
        rows = [r for r in size if r["lib"] == lib]
        if not rows:
            continue
        if lib == "fftchode":
            rows = rows[:1]
        elif lib == "ffte":
            L.append("| %s (double only) | %s | %s |" % (LIBNAMES[lib], rows[0]["artifact_file_bytes"], rows[0]["text"]))
            continue
        L.append("| %s | %d | %d |" % (LIBNAMES[lib], sum(int(r["artifact_file_bytes"]) for r in rows), sum(int(r["text"]) for r in rows)))
    L.append("")

with open(os.path.join(out, "SUMMARY.md"), "w") as f:
    f.write("\n".join(L) + "\n")
print("wrote", os.path.join(out, "SUMMARY.md"))
